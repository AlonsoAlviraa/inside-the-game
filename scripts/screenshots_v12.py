"""v12 screenshots: tour, best-moments reel, 3 viewers, ask-with-tools trace, colour-blind palette, mobile.
python scripts/screenshots_v12.py <url> [out] [prefix]"""
import sys
import time

from playwright.sync_api import sync_playwright

base, out = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "docs/screenshots")
pre = sys.argv[3] if len(sys.argv) > 3 else "v12"
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 1280, "height": 800})
    errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(base, wait_until="networkidle")
    time.sleep(2.5)
    pg.screenshot(path=f"{out}/{pre}-tour.png")
    for _ in range(2):
        pg.click("#tnext")
        time.sleep(0.5)
    pg.screenshot(path=f"{out}/{pre}-tour-best.png")
    pg.click("#tskip")
    pg.select_option("#match", "58")
    time.sleep(2)
    pg.click("#best")
    time.sleep(6.5)
    pg.screenshot(path=f"{out}/{pre}-best-moments.png")
    pg.keyboard.press("Escape")
    pg.click("#pvbtn")
    time.sleep(2)
    pg.screenshot(path=f"{out}/{pre}-three-viewers.png")
    pg.keyboard.press("Escape")
    pg.click('#tabs button[data-p="ask"]')
    pg.fill("#q", "show me all shots by Rafe Vance")
    pg.press("#q", "Enter")
    time.sleep(2.5)
    pg.click("details.trace summary")
    time.sleep(0.5)
    pg.screenshot(path=f"{out}/{pre}-ask-tools.png")
    pg.fill("#q", "compare teams in 2nd half")
    pg.press("#q", "Enter")
    time.sleep(2.5)
    pg.screenshot(path=f"{out}/{pre}-ask-compare.png")
    pg.click("#cvd")
    pg.click('#speed button[data-v="40"]')
    pg.click("#go")
    time.sleep(20)
    pg.screenshot(path=f"{out}/{pre}-colourblind-live.png")
    pg.click("#cvd")
    pg.keyboard.press("?")
    time.sleep(0.4)
    pg.screenshot(path=f"{out}/{pre}-keyboard-help.png")
    pg.keyboard.press("Escape")
    pg.evaluate("fullTime()")
    time.sleep(2)
    pg.screenshot(path=f"{out}/{pre}-fulltime.png")
    pg.click("text=Watch the condensed match")
    time.sleep(5)
    pg.screenshot(path=f"{out}/{pre}-condensed.png")
    m = b.new_page(viewport={"width": 390, "height": 844}, is_mobile=True)
    m.on("pageerror", lambda e: errs.append("mobile: " + str(e)))
    m.goto(base + "/?notour=1", wait_until="networkidle")
    time.sleep(2)
    m.click("#best")
    time.sleep(6)
    m.screenshot(path=f"{out}/{pre}-mobile.png")
    print("errors:", errs)
    b.close()
